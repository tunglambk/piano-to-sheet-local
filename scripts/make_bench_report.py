#!/usr/bin/env python3
"""Render the benchmark results as one static HTML page (Phase 3 deliverable).

Reads every `data/bench/results/*.json` written by `p2s-bench run` and writes
`bench/reports/v1/index.html` — the table the phase report links to, with n, the
95% CI, n_fail and the per-item values, so a reviewer never has to trust a number
copied into prose.
"""

from __future__ import annotations

import html
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "data" / "bench" / "results"
OUT = REPO / "bench" / "reports" / "v1" / "index.html"

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>P2S benchmark results</title>
<style>
 body {{ font: 15px/1.5 system-ui, sans-serif; margin: 2rem auto; max-width: 60rem; color: #111; }}
 h1 {{ font-size: 1.5rem; }} h2 {{ font-size: 1.15rem; margin-top: 2rem; }}
 table {{ border-collapse: collapse; width: 100%; margin: .5rem 0 1rem; }}
 th, td {{ border: 1px solid #ddd; padding: .35rem .5rem; text-align: right; }}
 th:first-child, td:first-child {{ text-align: left; }}
 caption {{ text-align: left; color: #555; font-size: .9rem; padding-bottom: .3rem; }}
 .fail {{ color: #b00; }} .muted {{ color: #666; }}
</style>
</head>
<body>
<h1>P2S benchmark results</h1>
<p class="muted">Generated by <code>scripts/make_bench_report.py</code> from
<code>data/bench/results/</code>. Every row comes from one <code>p2s-bench run</code>;
failed items are counted, never dropped.</p>
{sections}
</body>
</html>
"""

SECTION = """<h2>{suite} — {system}</h2>
<table>
<caption>split {split} · n = {n} · failed = {fails} · mean {mean} · 95% CI [{low}, {high}]</caption>
<thead><tr><th>item</th><th>condition</th><th>OMR-NED</th><th>note F1</th><th>playback</th><th>seconds</th></tr></thead>
<tbody>{rows}</tbody>
</table>"""


def _fmt(value: object) -> str:
    return "—" if value is None else f"{float(value):.3f}"


def render() -> Path:
    sections = []
    if RESULTS.exists():
        for path in sorted(RESULTS.glob("*.json")):
            data = json.loads(path.read_text())
            summary = data.get("summary", {})
            ci = summary.get("ci95") or [None, None]
            rows = []
            for item in data.get("items", []):
                status = item.get("status")
                cell = (
                    _fmt(item.get("omr_ned"))
                    if status == "ok"
                    else f'<span class="fail">{html.escape(str(status))}</span>'
                )
                rows.append(
                    "<tr>"
                    f"<td>{html.escape(str(item.get('id')))}</td>"
                    f"<td>{html.escape(str(item.get('condition') or '—'))}</td>"
                    f"<td>{cell}</td>"
                    f"<td>{_fmt(item.get('note_f1'))}</td>"
                    f"<td>{_fmt(item.get('playback'))}</td>"
                    f"<td>{_fmt(item.get('seconds'))}</td>"
                    "</tr>"
                )
            sections.append(
                SECTION.format(
                    suite=html.escape(str(summary.get("suite", path.stem))),
                    system=html.escape(str(summary.get("system", "unknown"))),
                    split=html.escape(str(summary.get("split", "?"))),
                    n=summary.get("n_items", len(rows)),
                    fails=summary.get("n_fail", "?"),
                    mean=_fmt(summary.get("mean")),
                    low=_fmt(ci[0]),
                    high=_fmt(ci[1]),
                    rows="".join(rows),
                )
            )
    if not sections:
        sections.append("<p>No results yet: run <code>python -m p2s.bench_cli run …</code> first.</p>")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(PAGE.format(sections="\n".join(sections)))
    return OUT


if __name__ == "__main__":
    print(render())
